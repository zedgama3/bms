// Reads every messages/<lang>.json of the shell and of each set and writes
// src/i18n/keys.d.ts (decision 8). `--check` fails when the committed file is out of date.
// Other languages may be incomplete: missing keys are printed as a warning, not a failure.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "src");

export function catalogueDirs(srcDir = src) {
  const dirs = [path.join(srcDir, "shell", "messages")];
  for (const area of ["modules", "core"]) {
    const base = path.join(srcDir, area);
    if (!fs.existsSync(base)) continue;
    for (const e of fs.readdirSync(base, { withFileTypes: true })) {
      const d = path.join(base, e.name, "messages");
      if (e.isDirectory() && fs.existsSync(d)) dirs.push(d);
    }
  }
  return dirs;
}

function readFlat(file) {
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  if (data === null || typeof data !== "object" || Array.isArray(data)) {
    throw new Error(`${file}: must be a flat JSON object`);
  }
  for (const [k, v] of Object.entries(data)) {
    if (typeof v !== "string") throw new Error(`${file}: ${k} must be a string`);
  }
  return data;
}

/** Returns { dts, missing } for a source tree. */
export function generate(srcDir = src) {
  const keys = new Map(); // key -> file that defined it
  const langs = new Map(); // lang -> Set of keys
  for (const dir of catalogueDirs(srcDir)) {
    const en = path.join(dir, "en.json");
    if (!fs.existsSync(en)) throw new Error(`${dir}: en.json is required`);
    for (const f of fs.readdirSync(dir).filter((n) => n.endsWith(".json"))) {
      const lang = f.slice(0, -5);
      const data = readFlat(path.join(dir, f));
      if (!langs.has(lang)) langs.set(lang, new Set());
      for (const k of Object.keys(data)) {
        langs.get(lang).add(k);
        if (lang === "en") {
          if (keys.has(k)) throw new Error(`key ${k} is defined in ${keys.get(k)} and in ${en}`);
          keys.set(k, en);
        }
      }
    }
  }
  const sorted = [...keys.keys()].sort();
  const dts =
    "// Generated by `pnpm generate:messages`. Do not edit.\n" +
    "export interface GeneratedKeys {\n" +
    sorted.map((k) => `  ${JSON.stringify(k)}: true;\n`).join("") +
    "}\n";
  const missing = {};
  for (const [lang, set] of langs) {
    if (lang === "en") continue;
    missing[lang] = sorted.filter((k) => !set.has(k));
  }
  return { dts, missing };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(src, "i18n", "keys.d.ts");
  const { dts, missing } = generate();
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
    if (have !== dts) {
      console.error("src/i18n/keys.d.ts is out of date: run `pnpm generate:messages`");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(out, dts);
  }
  for (const [lang, keys] of Object.entries(missing)) {
    if (keys.length > 0)
      console.warn(`warning: ${lang} lacks ${keys.length} key(s): ${keys.join(", ")}`);
  }
}
