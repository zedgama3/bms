/** Every key in web/src/shell/messages/en.json and every set's messages/en.json, as a union
 *  generated by `pnpm generate:messages` (decision 8). */
export type MessageKey = keyof GeneratedKeys;

export type MessageValues = Record<string, string | number | Date | boolean>;
export type Translate = (key: MessageKey, values?: MessageValues) => string;

/** Runtime guard over the loaded `en` catalogues: true when s is a key of the shell's or any
 *  registered set's catalogue. Pure; never throws (decision 23). */
export function isMessageKey(s: string): s is MessageKey {
  return Object.hasOwn(mergedFor("en"), s);
}

/** Provides the active language and its messages (the English text under any key a language
 *  lacks, F23). Mounted once by the frame, above everything that translates. */
export function I18nProvider({ children }: { children: ReactNode }): ReactNode {
  const lang = useSyncExternalStore(subscribeLanguage, getLanguage);
  const loaded = useSyncExternalStore(subscribeCatalogues, catalogueVersion);
  const messages = useMemo(
    () => ({ ...mergedFor("en"), ...(lang === "en" ? {} : mergedFor(lang)) }),
    // `loaded` changes whenever a catalogue is added, so the merge is redone
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [lang, loaded],
  );
  return (
    <IntlProvider locale={lang} defaultLocale="en" messages={messages} onError={recordError}>
      {children}
    </IntlProvider>
  );
}

const warned = new Set<string>();

/** F23: in development, one warning per key that a non-English language lacks (the English
 *  text is shown). Production stays silent; `generate:messages` lists the gaps. */
function warnMissing(lang: string, key: string): void {
  if (!import.meta.env.DEV || lang === "en") return;
  const id = `${lang}:${key}`;
  if (warned.has(id) || Object.hasOwn(mergedFor(lang), key)) return;
  warned.add(id);
  console.warn(`i18n: "${key}" has no ${lang} translation; showing English`);
}

/** Tests only. */
export function resetMissingWarningsForTest(): void {
  warned.clear();
}

// FormatJS does not throw for a missing argument or a malformed message: it reports to the
// provider's `onError` and returns the raw source text. `formatMessage` is synchronous, so a
// call clears this, formats, and checks it; any error recorded in between came from that call
// (the nearest provider's `onError` is the only one it can reach), whatever StrictMode or
// concurrent rendering does around it.
let lastError: unknown = null;
function recordError(err: unknown): void {
  lastError = err;
}

const warnedFormat = new Set<string>();

/** F24a: in development, one warning per key and language that cannot be formatted. */
function warnFormat(lang: string, key: string, shown: "English" | "the key"): void {
  if (!import.meta.env.DEV) return;
  const id = `${lang}:${key}`;
  if (warnedFormat.has(id)) return;
  warnedFormat.add(id);
  console.warn(`i18n: "${key}" cannot be formatted in ${lang}; showing ${shown}`);
}

/** Tests only. */
export function resetFormatWarningsForTest(): void {
  warnedFormat.clear();
}

type Formatted = ReactNode;

/** Formats key; null when FormatJS reported any error or threw. */
function tryFormat(
  intl: IntlShape,
  key: string,
  values: Record<string, unknown>,
): Formatted | null {
  lastError = null;
  try {
    const out: Formatted = intl.formatMessage({ id: key }, values as never);
    return lastError === null ? out : null;
  } catch {
    return null;
  } finally {
    lastError = null;
  }
}

let enIntl: { messages: object; intl: IntlShape } | null = null;
/** The `en` formatter, rebuilt only when the merged `en` catalogue object changes. */
function englishIntl(): IntlShape {
  const messages = mergedFor("en");
  if (enIntl?.messages !== messages) {
    enIntl = {
      messages,
      intl: createIntl({ locale: "en", messages, onError: recordError }),
    };
  }
  return enIntl.intl;
}

/** F23/F24/F24a: the active language's text, else the `en` text with the same values, else the
 *  key. Never throws. */
function formatOrFallback(
  intl: IntlShape,
  key: string,
  values: Record<string, unknown>,
): Formatted {
  warnMissing(intl.locale, key);
  const out = tryFormat(intl, key, values);
  if (out !== null) return out;
  if (!Object.hasOwn(intl.messages, key)) return key; // F24: not a message at all
  if (intl.locale !== "en") {
    const fallback = tryFormat(englishIntl(), key, values);
    if (fallback !== null) {
      warnFormat(intl.locale, key, "English");
      return fallback;
    }
  }
  warnFormat(intl.locale, key, "the key");
  return key;
}

/** Returns the message for key in the active language, with values interpolated (`Date` and
 *  `boolean` values are only meaningful in `date`/`time`/`select` arguments) and the
 *  regional's terms available as {term_event}, ... Falls back to `en`, then to the key
 *  itself (F23, F24, F24a: a message that cannot be formatted, e.g. a missing argument).
 *  Never throws. */
export function useT(): Translate {
  const intl = useIntl();
  return useCallback(
    (key, values) => {
      const out = formatOrFallback(intl, key, {
        ...termsOf(intl.messages as Record<string, string>),
        ...values,
      });
      return typeof out === "string" ? out : key;
    },
    [intl],
  );
}

/** Like useT for a message with rich-text tags: `<en>{reason}</en>` becomes
 *  `<span lang="en">` (decision 2). Same fallbacks as useT. Never throws. */
export function useRichT(): (key: MessageKey, values?: RichValues) => ReactNode {
  const intl = useIntl();
  return useCallback(
    (key, values) =>
      formatOrFallback(intl, key, {
        ...termsOf(intl.messages as Record<string, string>),
        en: (chunks: ReactNode[]) => <span lang="en">{chunks}</span>,
        ...values,
      }),
    [intl],
  );
}

export type RichValues = Record<
  string,
  string | number | Date | boolean | ((chunks: ReactNode[]) => ReactNode)
>;

export interface Format {
  date(instant: string | Date, zone?: string): string;
  time(instant: string | Date, zone?: string): string;
  dateTime(instant: string | Date, zone?: string): string;
  number(n: number): string;
  /** A size such as "2 MB" (1024-based steps). */
  bytes(n: number): string;
  relative(instant: string | Date): string;
  list(items: string[]): string;
}

function toDate(v: string | Date): Date | null {
  const d = v instanceof Date ? v : new Date(v);
  return Number.isNaN(d.getTime()) ? null : d;
}

function validZone(zone: string | undefined): string | undefined {
  if (!zone) return undefined;
  try {
    new Intl.DateTimeFormat("en", { timeZone: zone });
    return zone;
  } catch {
    return undefined;
  }
}

/** Locale-aware formatting through Intl, in the active language. `date` and `time` take an
 *  IANA zone (an event's) and show the zone when it differs from the browser's. */
export function makeFormat(locale: string): Format {
  const browserZone = new Intl.DateTimeFormat().resolvedOptions().timeZone;
  const fmt = (
    v: string | Date,
    zone: string | undefined,
    o: Intl.DateTimeFormatOptions,
    showZone: boolean,
  ) => {
    const d = toDate(v);
    if (!d) return "";
    const z = validZone(zone);
    const opts: Intl.DateTimeFormatOptions = { ...o };
    if (z) opts.timeZone = z;
    if (showZone && z && z !== browserZone) opts.timeZoneName = "short";
    return new Intl.DateTimeFormat(locale, opts).format(d);
  };
  const dateOpts: Intl.DateTimeFormatOptions = { year: "numeric", month: "short", day: "numeric" };
  const timeOpts: Intl.DateTimeFormatOptions = { hour: "numeric", minute: "2-digit" };
  return {
    date: (v, zone) => fmt(v, zone, dateOpts, false),
    time: (v, zone) => fmt(v, zone, timeOpts, true),
    dateTime: (v, zone) => fmt(v, zone, { ...dateOpts, ...timeOpts }, true),
    number: (n) => new Intl.NumberFormat(locale).format(n),
    bytes: (n) => {
      const units = ["byte", "kilobyte", "megabyte", "gigabyte"] as const;
      let i = 0;
      let v = Math.max(0, n);
      while (v >= 1024 && i < units.length - 1) {
        v /= 1024;
        i++;
      }
      return new Intl.NumberFormat(locale, {
        style: "unit",
        unit: units[i] ?? "byte",
        unitDisplay: "short",
        maximumFractionDigits: i === 0 ? 0 : 1,
      }).format(v);
    },
    relative: (v) => {
      const d = toDate(v);
      if (!d) return "";
      const seconds = Math.round((d.getTime() - Date.now()) / 1000);
      const units: [Intl.RelativeTimeFormatUnit, number][] = [
        ["day", 86400],
        ["hour", 3600],
        ["minute", 60],
      ];
      const rtf = new Intl.RelativeTimeFormat(locale, { numeric: "auto" });
      for (const [unit, size] of units) {
        if (Math.abs(seconds) >= size) return rtf.format(Math.round(seconds / size), unit);
      }
      return rtf.format(seconds, "second");
    },
    list: (items) =>
      new Intl.ListFormat(locale, { style: "long", type: "conjunction" }).format(items),
  };
}

export function useFormat(): Format {
  const lang = useSyncExternalStore(subscribeLanguage, getLanguage);
  return useMemo(() => makeFormat(lang), [lang]);
}

/** The active language and the ones offered. `set` persists the choice and re-renders. */
export function useLanguage(): {
  current: string;
  offered: readonly string[];
  set: (tag: string) => void;
} {
  const current = useSyncExternalStore(subscribeLanguage, getLanguage);
  const offered = useSyncExternalStore(subscribeLanguage, getOffered);
  return { current, offered, set: setLanguage };
}
